using System;
using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.ScriptableObjects;
using Object = UnityEngine.Object;

namespace bHaptics.VRChatAvatar
{
    /// Carries out an IndicatorPlan on copies: the FX and Expression Parameters in the descriptor's slots are copied, ours is removed
    /// from the copies and written again, and the slots point at the copies. The originals are never edited.
    public static class IndicatorApplier
    {
        public const string AssetKey = "bHaptics";
        private const string ClipPrefix = "zAutogenerated/" + AssetKey + "__"; // how AAC names the clips it creates

        /// Writes the layers into the FX, with the avatar root and the controller's Write Defaults; set by the AAC assembly when AAC is installed.
        public static Action<AnimatorController, IReadOnlyList<IndicatorLayer>, Transform, bool> LayerWriter;

        /// Plan for the build target's platform and apply. Returns the plan; when it has blockers nothing changed.
        public static IndicatorPlan Apply(HapticsSetup setup)
        {
            return Apply(setup, IndicatorPlanner.Plan(setup, Platforms.IsBuildTargetMobile()));
        }

        /// Apply plan to setup's avatar. Undo puts the slots back; the copies stay on disk, since asset creation isn't undoable.
        public static IndicatorPlan Apply(HapticsSetup setup, IndicatorPlan plan)
        {
            if (plan.layers.Count > 0 && LayerWriter == null)
            {
                plan.blockers.Add("Indicators need Animator As Code. Add hai-vr's listing to VCC and install it.");
            }

            if (plan.blockers.Count > 0)
            {
                Debug.LogWarning($"[bHaptics] Indicators weren't applied: {string.Join(" ", plan.blockers)}", setup);
                return plan;
            }

            if (plan.IsUpToDate)
            {
                return plan;
            }

            var descriptor = setup.GetComponent<VRCAvatarDescriptor>();
            var time = DateTime.Now;
            var fx = plan.ChangesFx ? WriteFx(plan, setup.transform, time) : null;
            var parameters = plan.ChangesParameters ? WriteParameters(plan, setup.name, time) : null;
            var menu = plan.copiesDefaultMenu ? CopyDefaultMenu(parameters, setup.name, time) : null;
            AssetDatabase.SaveAssets();

            // The asset work above leaves no Undo records (WriteFx clears the copy's), so this one is Apply's only record and stays right before its writes.
            Undo.RecordObject(descriptor, "Apply bHaptics Indicators");
            if (fx != null)
            {
                SetFx(descriptor, fx);
            }

            if (parameters != null)
            {
                descriptor.customExpressions = true;
                descriptor.expressionParameters = parameters;
                if (menu != null)
                {
                    descriptor.expressionsMenu = menu;
                }
            }

            PrefabUtility.RecordPrefabInstancePropertyModifications(descriptor);
            Debug.Log($"[bHaptics] Applied indicators: {plan.layers.Count} layers, {plan.bitsAfter} synced bits.", setup);
            return plan;
        }

        /// Copy the FX, or create one, remove our layers, clips and parameters from it, and write the planned layers.
        private static AnimatorController WriteFx(IndicatorPlan plan, Transform avatarRoot, DateTime time)
        {
            GeneratedAssets.CreateFolder();
            var fx = plan.fx != null
                ? GeneratedAssets.Copy(plan.fx, plan.fx.name, time)
                : AnimatorController.CreateAnimatorControllerAtPath(GeneratedAssets.GetPath($"{avatarRoot.name}_FX", "controller", time));

            var path = AssetDatabase.GetAssetPath(fx);
            var writeDefaults = GetWriteDefaults(fx);
            // The legacy package's clips carry a random key per avatar, so they're known only by the layers that play them.
            var legacyClips = new HashSet<Motion>(fx.layers.Where(l => l.name.StartsWith(IndicatorPlanner.LegacyLayerPrefix)).SelectMany(l => GetMotions(l.stateMachine)));
            // RemoveLayer destroys through Undo, so one Ctrl+Z would half-revert the copy; drop the layers from the list and their parts directly.
            var dropped = fx.layers.Where(IsOurs).ToList();
            fx.layers = fx.layers.Where(l => !IsOurs(l)).ToArray();
            // A motion a kept layer still plays, such as a shared blend tree, stays.
            var kept = new HashSet<Motion>(fx.layers.SelectMany(l => GetMotions(l.stateMachine)));
            foreach (var part in dropped.SelectMany(l => GetParts(l.stateMachine))
                         .Where(p => p != null && AssetDatabase.GetAssetPath(p) == path && !kept.Contains(p as Motion)).Distinct().ToList())
            {
                AssetDatabase.RemoveObjectFromAsset(part);
                Object.DestroyImmediate(part, true);
            }

            foreach (var parameter in fx.parameters.Where(p => plan.fxParametersToRemove.Contains(p.name) || plan.fxParametersToRetype.Contains(p.name)).ToList())
            {
                fx.RemoveParameter(parameter);
            }

            RemoveUnusedClips(fx, legacyClips);
            if (plan.layers.Count > 0)
            {
                LayerWriter(fx, plan.layers, avatarRoot, writeDefaults);
                // AAC leaves a placeholder clip per layer that no state plays.
                RemoveUnusedClips(fx, legacyClips);
            }

            // The copy's creation isn't undoable, so its edits shouldn't be either: Undo puts the slot back and leaves the copy as written.
            foreach (var asset in AssetDatabase.LoadAllAssetsAtPath(path))
            {
                Undo.ClearUndo(asset);
            }

            EditorUtility.SetDirty(fx);
            return fx;
        }

        /// Get machine and what's stored under it in the controller: sub-state machines, states, transitions, behaviours and blend trees.
        private static IEnumerable<Object> GetParts(AnimatorStateMachine machine)
        {
            if (machine == null)
            {
                yield break;
            }

            yield return machine;
            foreach (var transition in machine.anyStateTransitions)
            {
                yield return transition;
            }

            foreach (var transition in machine.entryTransitions)
            {
                yield return transition;
            }

            foreach (var behaviour in machine.behaviours)
            {
                yield return behaviour;
            }

            foreach (var state in machine.states.Select(s => s.state).Where(s => s != null))
            {
                yield return state;
                foreach (var transition in state.transitions)
                {
                    yield return transition;
                }

                foreach (var behaviour in state.behaviours)
                {
                    yield return behaviour;
                }

                foreach (var tree in GetTrees(state.motion))
                {
                    yield return tree;
                }
            }

            foreach (var child in machine.stateMachines)
            {
                foreach (var transition in machine.GetStateMachineTransitions(child.stateMachine))
                {
                    yield return transition;
                }

                foreach (var part in GetParts(child.stateMachine))
                {
                    yield return part;
                }
            }
        }

        /// Returns the Write Defaults most of the controller's own states use, so our layers match; off when it has none.
        private static bool GetWriteDefaults(AnimatorController fx)
        {
            var states = fx.layers.Where(l => !IsOurs(l) && l.stateMachine != null).SelectMany(l => l.stateMachine.states).Select(s => s.state).Where(s => s != null).ToList();
            return states.Count(s => s.writeDefaultValues) > states.Count / 2f;
        }

        /// Returns true for our layers and the legacy package's, which Apply replaces.
        private static bool IsOurs(AnimatorControllerLayer layer)
        {
            return layer.name.StartsWith(IndicatorPlanner.Prefix) || layer.name.StartsWith(IndicatorPlanner.LegacyLayerPrefix);
        }

        /// Remove the clips embedded in fx that are ours, or among legacyClips, and that nothing in fx plays any more.
        private static void RemoveUnusedClips(AnimatorController fx, HashSet<Motion> legacyClips)
        {
            var used = new HashSet<Motion>(fx.layers.SelectMany(l => GetMotions(l.stateMachine)));
            var path = AssetDatabase.GetAssetPath(fx);
            foreach (var clip in AssetDatabase.LoadAllAssetsAtPath(path).OfType<AnimationClip>()
                         .Where(c => (c.name.StartsWith(ClipPrefix) || legacyClips.Contains(c)) && !used.Contains(c)).ToList())
            {
                AssetDatabase.RemoveObjectFromAsset(clip);
                Object.DestroyImmediate(clip, true);
            }
        }

        private static IEnumerable<BlendTree> GetTrees(Motion motion)
        {
            var tree = motion as BlendTree;
            if (tree == null)
            {
                yield break;
            }

            yield return tree;
            foreach (var child in tree.children)
            {
                foreach (var nested in GetTrees(child.motion))
                {
                    yield return nested;
                }
            }
        }

        /// Get every motion machine plays, inside blend trees and sub-state machines too; a broken layer's missing parts give none.
        private static IEnumerable<Motion> GetMotions(AnimatorStateMachine machine)
        {
            if (machine == null)
            {
                return Enumerable.Empty<Motion>();
            }

            return machine.states.Where(s => s.state != null).SelectMany(s => Expand(s.state.motion))
                .Concat(machine.stateMachines.SelectMany(m => GetMotions(m.stateMachine)));
        }

        private static IEnumerable<Motion> Expand(Motion motion)
        {
            if (motion == null)
            {
                return Enumerable.Empty<Motion>();
            }

            var tree = motion as BlendTree;
            if (tree == null)
            {
                return new[] { motion };
            }

            return tree.children.SelectMany(c => Expand(c.motion)).Prepend(motion);
        }

        /// Copy the slot's parameters, or VRChat's defaults, with ours fixed where they stand, without the Bools that go, and with the new ones at the end, so the rest keep their positions.
        private static VRCExpressionParameters WriteParameters(IndicatorPlan plan, string avatarName, DateTime time)
        {
            var source = IndicatorPlanner.GetSourceParameters(plan);
            var parameters = GeneratedAssets.Copy(source, plan.parameters != null ? source.name : $"{avatarName}_Parameters", time);
            foreach (var parameter in parameters.parameters.Where(p => plan.boolsToFix.Contains(p.name)))
            {
                parameter.valueType = VRCExpressionParameters.ValueType.Bool;
                parameter.networkSynced = true;
                parameter.saved = false;
                parameter.defaultValue = 0f;
            }

            parameters.parameters = parameters.parameters
                .Where(p => !plan.boolsToRemove.Contains(p.name))
                .Concat(plan.boolsToAdd.Select(name => new VRCExpressionParameters.Parameter
                {
                    name = name,
                    valueType = VRCExpressionParameters.ValueType.Bool,
                    networkSynced = true,
                }))
                .ToArray();
            EditorUtility.SetDirty(parameters);
            return parameters;
        }

        /// Copy VRChat's default menu, pointed at parameters.
        private static VRCExpressionsMenu CopyDefaultMenu(VRCExpressionParameters parameters, string avatarName, DateTime time)
        {
            var menu = GeneratedAssets.Copy(AssetDatabase.LoadAssetAtPath<VRCExpressionsMenu>(IndicatorPlanner.DefaultMenuPath), $"{avatarName}_Menu", time);
            menu.Parameters = parameters;
            EditorUtility.SetDirty(menu);
            return menu;
        }

        /// Point descriptor's FX slot at fx, customizing the playable layers if they were left at VRChat's defaults.
        private static void SetFx(VRCAvatarDescriptor descriptor, AnimatorController fx)
        {
            descriptor.customizeAnimationLayers = true;
            var layers = descriptor.baseAnimationLayers ?? Array.Empty<VRCAvatarDescriptor.CustomAnimLayer>();
            var index = Array.FindIndex(layers, l => l.type == VRCAvatarDescriptor.AnimLayerType.FX);
            if (index < 0)
            {
                layers = layers.Append(new VRCAvatarDescriptor.CustomAnimLayer { type = VRCAvatarDescriptor.AnimLayerType.FX }).ToArray();
                index = layers.Length - 1;
            }

            layers[index].isEnabled = true;
            layers[index].isDefault = false;
            layers[index].animatorController = fx;
            descriptor.baseAnimationLayers = layers;
        }
    }
}
