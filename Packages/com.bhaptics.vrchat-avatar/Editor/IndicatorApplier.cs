using System;
using System.Collections.Generic;
using System.Linq;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.ScriptableObjects;
using Object = UnityEngine.Object;

namespace bHaptics.VRChatAvatar
{
    /// Carries out an IndicatorPlan on copies: the FX and Expression Parameters in the descriptor's slots are copied, ours is removed
    /// from the copies and written again, and the slots point at the copies. The originals are never edited.
    public static class IndicatorApplier
    {
        public const string AssetKey = "bHaptics";
        private const string ClipPrefix = "zAutogenerated/" + AssetKey + "__"; // how AAC names the clips it creates

        /// Writes the layers into the FX, with the avatar root and the controller's Write Defaults; set by the AAC assembly when AAC is installed.
        public static Action<AnimatorController, IReadOnlyList<IndicatorLayer>, Transform, bool> LayerWriter;

        /// Plan for the build target's platform and apply. Returns the plan; when it has blockers nothing changed.
        public static IndicatorPlan Apply(HapticsSetup setup)
        {
            return Apply(setup, IndicatorPlanner.Plan(setup, Platforms.IsBuildTargetMobile()));
        }

        /// Apply plan to setup's avatar. Undo puts the slots back; the copies stay on disk, since asset creation isn't undoable.
        public static IndicatorPlan Apply(HapticsSetup setup, IndicatorPlan plan)
        {
            if (plan.layers.Count > 0 && LayerWriter == null)
            {
                plan.blockers.Add("Indicators need Animator As Code. Add hai-vr's listing to VCC and install it.");
            }

            if (plan.blockers.Count > 0)
            {
                Debug.LogWarning($"[bHaptics] Indicators weren't applied: {string.Join(" ", plan.blockers)}", setup);
                return plan;
            }

            if (plan.IsUpToDate)
            {
                return plan;
            }

            var descriptor = setup.GetComponent<VRCAvatarDescriptor>();
            var time = DateTime.Now;
            var fx = plan.ChangesFx ? WriteFx(plan, setup.transform, time) : null;
            var parameters = plan.ChangesParameters ? WriteParameters(plan, setup.name, time) : null;
            var menu = parameters != null && (!descriptor.customExpressions || descriptor.expressionsMenu == null) ? CopyDefaultMenu(parameters, setup.name, time) : null;
            AssetDatabase.SaveAssets();

            // The asset work above makes no Undo records, so this one stays right before its writes.
            Undo.RecordObject(descriptor, "Apply bHaptics Indicators");
            if (fx != null)
            {
                SetFx(descriptor, fx);
            }

            if (parameters != null)
            {
                descriptor.customExpressions = true;
                descriptor.expressionParameters = parameters;
                if (menu != null)
                {
                    descriptor.expressionsMenu = menu;
                }
            }

            PrefabUtility.RecordPrefabInstancePropertyModifications(descriptor);
            Debug.Log($"[bHaptics] Applied indicators: {plan.layers.Count} layers, {plan.bitsAfter} synced bits.", setup);
            return plan;
        }

        /// Copy the FX, or create one, remove our layers, clips and parameters from it, and write the planned layers.
        private static AnimatorController WriteFx(IndicatorPlan plan, Transform avatarRoot, DateTime time)
        {
            GeneratedAssets.CreateFolder();
            var fx = plan.fx != null
                ? GeneratedAssets.Copy(plan.fx, plan.fx.name, time)
                : AnimatorController.CreateAnimatorControllerAtPath(GeneratedAssets.GetPath($"{avatarRoot.name}_FX", "controller", time));

            var writeDefaults = GetWriteDefaults(fx);
            for (var i = fx.layers.Length - 1; i >= 0; i--)
            {
                if (fx.layers[i].name.StartsWith(IndicatorPlanner.Prefix))
                {
                    fx.RemoveLayer(i);
                }
            }

            foreach (var parameter in fx.parameters.Where(p => plan.fxParametersToRemove.Contains(p.name)).ToList())
            {
                fx.RemoveParameter(parameter);
            }

            RemoveUnusedClips(fx);
            if (plan.layers.Count > 0)
            {
                LayerWriter(fx, plan.layers, avatarRoot, writeDefaults);
                // AAC leaves a placeholder clip per layer that no state plays.
                RemoveUnusedClips(fx);
            }

            EditorUtility.SetDirty(fx);
            return fx;
        }

        /// Returns the Write Defaults most of the controller's own states use, so our layers match; off when it has none.
        private static bool GetWriteDefaults(AnimatorController fx)
        {
            var states = fx.layers.Where(l => !l.name.StartsWith(IndicatorPlanner.Prefix)).SelectMany(l => l.stateMachine.states).Select(s => s.state).ToList();
            return states.Count(s => s.writeDefaultValues) > states.Count / 2f;
        }

        /// Remove our clips that no state of fx plays.
        private static void RemoveUnusedClips(AnimatorController fx)
        {
            var used = new HashSet<Motion>(fx.layers.SelectMany(l => l.stateMachine.states).Select(s => s.state.motion));
            var path = AssetDatabase.GetAssetPath(fx);
            foreach (var clip in AssetDatabase.LoadAllAssetsAtPath(path).OfType<AnimationClip>().Where(c => c.name.StartsWith(ClipPrefix) && !used.Contains(c)).ToList())
            {
                AssetDatabase.RemoveObjectFromAsset(clip);
                Object.DestroyImmediate(clip, true);
            }
        }

        /// Copy the slot's parameters, or VRChat's defaults, without the Bools that go and with the new ones at the end, so the rest keep their positions.
        private static VRCExpressionParameters WriteParameters(IndicatorPlan plan, string avatarName, DateTime time)
        {
            var source = IndicatorPlanner.GetSourceParameters(plan);
            var parameters = GeneratedAssets.Copy(source, plan.parameters != null ? source.name : $"{avatarName}_Parameters", time);
            parameters.parameters = parameters.parameters
                .Where(p => !plan.boolsToRemove.Contains(p.name))
                .Concat(plan.boolsToAdd.Select(name => new VRCExpressionParameters.Parameter
                {
                    name = name,
                    valueType = VRCExpressionParameters.ValueType.Bool,
                    networkSynced = true,
                }))
                .ToArray();
            EditorUtility.SetDirty(parameters);
            return parameters;
        }

        /// Copy VRChat's default menu for an avatar that had no expressions of its own: the SDK refuses parameters without a menu.
        private static VRCExpressionsMenu CopyDefaultMenu(VRCExpressionParameters parameters, string avatarName, DateTime time)
        {
            var menu = GeneratedAssets.Copy(AssetDatabase.LoadAssetAtPath<VRCExpressionsMenu>(IndicatorPlanner.DefaultMenuPath), $"{avatarName}_Menu", time);
            menu.Parameters = parameters;
            EditorUtility.SetDirty(menu);
            return menu;
        }

        /// Point descriptor's FX slot at fx, customizing the playable layers if they were left at VRChat's defaults.
        private static void SetFx(VRCAvatarDescriptor descriptor, AnimatorController fx)
        {
            descriptor.customizeAnimationLayers = true;
            var layers = descriptor.baseAnimationLayers ?? Array.Empty<VRCAvatarDescriptor.CustomAnimLayer>();
            var index = Array.FindIndex(layers, l => l.type == VRCAvatarDescriptor.AnimLayerType.FX);
            if (index < 0)
            {
                layers = layers.Append(new VRCAvatarDescriptor.CustomAnimLayer { type = VRCAvatarDescriptor.AnimLayerType.FX }).ToArray();
                index = layers.Length - 1;
            }

            layers[index].isEnabled = true;
            layers[index].isDefault = false;
            layers[index].animatorController = fx;
            descriptor.baseAnimationLayers = layers;
        }
    }
}
